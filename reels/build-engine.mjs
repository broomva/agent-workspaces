// Extracts the deck's render kit (canvas helpers, liquid metal, glass-plasma WebGL orbs, ASCII text shader)
// from deck/index.html into reels/engine.js, so reels and the keynote share one source of truth.
// Usage: bun reels/build-engine.mjs   (re-run after changing the deck's render kit)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const lines = readFileSync(path.join(here, '..', 'deck', 'index.html'), 'utf8').split('\n');
const at = (prefix, from = 0) => {
  const i = lines.findIndex((l, k) => k >= from && l.startsWith(prefix));
  if (i < 0) throw new Error(`marker not found: ${prefix}`);
  return i;
};
// [start marker, end marker (exclusive)] pairs, copied verbatim
const ranges = [
  ['const C={};', 'function readColors()'],
  ['function readColors()', '/* canvas kit,'],
  ['const TAU=Math.PI*2', '/* Spring:'],
  ['const clear=c=>', 'function T(s,x,y'],
  ['const al=(c,a)=>', 'function ribbon('],
  ['/* liquid-metal ring', 'let METAL=true;'],
];
const out = [
  '// GENERATED by reels/build-engine.mjs from deck/index.html — do not edit; change the deck and re-run.',
  "const root=document.documentElement;let dirty=0;",
];
for (const [a, b] of ranges) {
  const s = at(a), e = at(b, s + 1);
  out.push(`/* ── from deck/index.html lines ${s + 1}-${e} ── */`, ...lines.slice(s, e));
}
out.push('let METAL=true;', 'readColors();');
out.push('/* exported for reel pages */',
  'Object.assign(window,{C,TAU,lerp,clamp,reseed,rnd,FONT,glow,dot,al,clear,metalGrad,fringe,metalRing,orb,orb2d,ORB,atlas,glyph,asciiField,FONTS_READY,setCtx:c=>{ctx=c},getCtx:()=>ctx});');
writeFileSync(path.join(here, 'engine.js'), out.join('\n') + '\n');
console.log(`reels/engine.js: ${out.length} lines`);
